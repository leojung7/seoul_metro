/* =============================================================================
   route-engine.js — travel-time aware, multi-route extension of the existing planner.

   * app.js plan() is UNCHANGED and remains the fallback (used if this file or travel-times.js fails to load).
   * Builds the same graph as plan() (stations x routes, same-line branch changes, cross-line transfers) but with
     times in SECONDS taken from the official data first (travel-times.js, generated by tools/build_travel_times.py).

   Ride time of one adjacent station pair, in order of preference
     1. "official"   exact running time (Seoul Metro file, Lines 1-8)                       -> used exactly
     2. "derived"    official distance (National Railway Authority file) -> time model      -> clearly flagged
     3. "estimated"  no official value: straight-line km x kappa -> the same time model     -> clearly flagged
   Time model (fitted on the exact segments):  seconds = fixedSec + secPerKm x km   (constants in TT.meta.model)

   Transfer time of one interchange
     1. "official"   exact walking time (Seoul Metro transfer file)
     2. "default"    Easy 2 min / Medium 4 min / Long 7 min  (configurable, see CFG)

   Station-stop (dwell) time: the official running times are departure -> arrival between stations and do NOT include the
   time trains stand in stations, so CFG.dwellSeconds is added at every intermediate station of a ride and shown separately.
   Waiting for the FIRST train is not included. After an official transfer walk an expected wait for the connecting train
   (CFG.transferWaitSeconds, default 120 s = half of a 3-5 min peak interval) is added and shown on its own line; without it a
   chain of quick transfers would look faster than a direct ride. Default-class transfers (Easy/Medium/Long) are complete
   penalties and get no extra wait.
   ========================================================================== */
(function () {
  "use strict";
  const TTD = (typeof TT !== "undefined" && TT && TT.ride) ? TT : { ride: {}, dist: {}, xfer: {}, meta: { model: { fixedSec: 23.9, secPerKm: 63.27, kappa: 1.036 }, sources: [] } };
  const MODEL = TTD.meta.model;

  // ---- configuration (override before this file loads:  window.TT_CONFIG = { dwellSeconds: 20 } ) ----
  const CFG = Object.assign({
    dwellSeconds: 25,                                       // time standing at each intermediate station (not in the official running times)
    transferDefaultsMin: { easy: 2, medium: 4, long: 7 },   // used only when no official transfer time exists
    transferDefaultClass: "medium",                         // class used when nothing else is known about a transfer
    transferClassOverrides: {},                             // "stationKo|lineA|lineB" -> "easy" | "medium" | "long"
    classThresholdsMin: { easy: 3, long: 5.5 },             // official walking minutes: < easy => easy, > long => long (line-pair median)
    transferWaitSeconds: 120,                               // expected wait for the connecting train after an OFFICIAL walking time (= half of a 3-5 min peak interval); not in any official file. 0 = off
    sameLineChangeSeconds: 12,                              // changing between branches of the same line (same value as plan(): 0.2 min)
    cruiseKmhByLine: {},                                    // optional per-line cruise speed override for derived/estimated segments
    alternates: { max: 2, maxRatio: 1.5, maxExtraSec: 1200, maxOverlap: 0.7 }
  }, (typeof window !== "undefined" && window.TT_CONFIG) || {});
  CFG.alternates = Object.assign({ max: 2, maxRatio: 1.5, maxExtraSec: 1200, maxOverlap: 0.7 }, CFG.alternates);

  // ---------------------------------------------------------------- helpers
  const rad = Math.PI / 180;
  function km(a, b) {
    const d = (b.lat - a.lat) * rad, e = (b.lng - a.lng) * rad;
    const h = Math.sin(d / 2) ** 2 + Math.cos(a.lat * rad) * Math.cos(b.lat * rad) * Math.sin(e / 2) ** 2;
    return 12742 * Math.asin(Math.sqrt(h));
  }
  const ekey = (g, A, B) => { const a = A.cd[g], b = B.cd[g]; return a < b ? g + "|" + a + "|" + b : g + "|" + b + "|" + a; };
  const xkey = (s, g1, g2) => { const a = g1 + ":" + s.cd[g1], b = g2 + ":" + s.cd[g2]; return a < b ? a + "|" + b : b + "|" + a; };
  // Time for a distance on a line that has no exact running time.
  //  * default: the calibrated model  fixedSec + secPerKm x km
  //  * "Include express lines" (ex === "x"): the app's existing per-line express speed (SPD in app.js) is used ONLY where it
  //    is faster than the model's own cruise speed - it stands for a faster service (airport / GTX type) and is never
  //    allowed to make a segment slower than the data-calibrated model.
  //  * CFG.cruiseKmhByLine overrides both once an official figure for a line exists.
  const MODEL_CRUISE = 3600 / MODEL.secPerKm;
  const timeModel = (g, kmv, ex) => {
    const spd = (ex === "x" && typeof SPD !== "undefined" && SPD[g] > MODEL_CRUISE) ? SPD[g] : 0;
    const cruise = CFG.cruiseKmhByLine[g] || spd;
    return cruise ? MODEL.fixedSec + (kmv / cruise) * 3600 : MODEL.fixedSec + MODEL.secPerKm * kmv;
  };

  // ---- one adjacent station pair on a line ----
  function rideSegment(g, A, B, ex) {
    const key = ekey(g, A, B), o = TTD.ride[key];
    if (o && o[0] > 0) return { sec: o[0], km: o[1] > 0 ? o[1] : km(A, B) * MODEL.kappa, tier: "official" };
    const d = TTD.dist[key];
    if (d > 0) return { sec: Math.round(timeModel(g, d, ex)), km: d, tier: "derived" };
    const k = km(A, B) * MODEL.kappa;
    return { sec: Math.round(timeModel(g, k, ex)), km: k, tier: "estimated" };
  }

  // ---- one interchange ----
  let pairMedians = null;
  function linePairMedianMin(g1, g2) {
    if (!pairMedians) {
      pairMedians = {};
      for (const k in TTD.xfer) {
        const [p, q] = k.split("|"), a = p.split(":")[0], b = q.split(":")[0], pk = a < b ? a + "|" + b : b + "|" + a;
        (pairMedians[pk] = pairMedians[pk] || []).push(TTD.xfer[k][1] / 60);
      }
    }
    const pk = g1 < g2 ? g1 + "|" + g2 : g2 + "|" + g1, arr = pairMedians[pk];
    if (!arr || arr.length < 2) return null;
    const s = arr.slice().sort((x, y) => x - y);
    return s[Math.floor(s.length / 2)];
  }
  function transferTime(s, g1, g2) {
    const w = CFG.transferWaitSeconds || 0;
    const o = TTD.xfer[xkey(s, g1, g2)];
    if (o) return { sec: o[1] + w, walkSec: o[1], waitSec: w, meters: o[0], src: "official", cls: null };
    const ov = CFG.transferClassOverrides[s.ko + "|" + g1 + "|" + g2] || CFG.transferClassOverrides[s.ko + "|" + g2 + "|" + g1];
    let cls = ov, via = ov ? "override" : null;
    if (!cls) {
      const med = linePairMedianMin(g1, g2);
      if (med != null) { cls = med < CFG.classThresholdsMin.easy ? "easy" : med > CFG.classThresholdsMin.long ? "long" : "medium"; via = "line-pair"; }
    }
    if (!cls) { cls = CFG.transferDefaultClass; via = "default"; }
    const walk = CFG.transferDefaultsMin[cls] * 60;
    return { sec: walk, walkSec: walk, waitSec: 0, meters: null, src: "default", cls, via };   // a default class is already the whole transfer
  }

  // ---------------------------------------------------------------- graph (state = station | route | riding?)
  // mode 0 = just boarded at this station, mode 1 = arrived by train. A station stop (dwell) is paid when the train
  // continues through a station (arrived -> next ride), so path cost == displayed time exactly (no hidden constants).
  const GRAPHS = {};
  function graph(ex) {
    const gk = ex === "x" ? "x" : "l";
    if (GRAPHS[gk]) return GRAPHS[gk];
    const ids = new Map(), adj = [], starts = {}, nodeOf = (s, r, m) => {
      const k = s + "|" + r + "|" + m; let i = ids.get(k);
      if (i == null) { i = adj.length; ids.set(k, i); adj.push([]); }
      return i;
    };
    const routes = RT.filter(r => r && Array.isArray(r.a) && D.L[r.g]);
    const stationRoutes = {};
    routes.forEach(r => r.a.forEach(si => (stationRoutes[si] = stationRoutes[si] || []).includes(r) || stationRoutes[si].push(r)));
    const addRide = (r, u, v) => {
      if (u === v || !ST[u] || !ST[v]) return;
      const seg = rideSegment(r.g, ST[u], ST[v], ex);
      const e = { k: "r", a: u, b: v, r, km: seg.km, sec: seg.sec, t: seg.sec / 60, tier: seg.tier };
      const eid = r.id + ":" + Math.min(u, v) + "-" + Math.max(u, v);
      e.id = eid;
      adj[nodeOf(u, r.id, 0)].push([nodeOf(v, r.id, 1), seg.sec, e]);
      adj[nodeOf(u, r.id, 1)].push([nodeOf(v, r.id, 1), seg.sec + CFG.dwellSeconds, e]);
    };
    routes.forEach(r => {
      const A = r.a;
      for (let i = 0; i < A.length - 1; i++) { addRide(r, A[i], A[i + 1]); addRide(r, A[i + 1], A[i]); }
      if (r.loop && r.id !== "6l" && A.length > 1) { addRide(r, A[A.length - 1], A[0]); addRide(r, A[0], A[A.length - 1]); }
    });
    Object.keys(stationRoutes).forEach(si => {
      const s = ST[si], rs = stationRoutes[si];
      rs.forEach(r1 => rs.forEach(r2 => {
        if (r1 === r2) return;
        const same = r1.g === r2.g, tt = same ? { sec: CFG.sameLineChangeSeconds, walkSec: CFG.sameLineChangeSeconds, src: "same-line", cls: null } : transferTime(s, r1.g, r2.g);
        const e = { k: "t", s, g1: r1.g, g2: r2.g, w: same ? 0 : tt.walkSec / 60, waitSec: same ? 0 : (tt.waitSec || 0), sec: tt.sec, t: tt.sec / 60, src: tt.src, cls: tt.cls, via: tt.via, meters: tt.meters || null };
        adj[nodeOf(+si, r1.id, 1)].push([nodeOf(+si, r2.id, 0), tt.sec, e]);
      }));
    });
    GRAPHS[gk] = { ids, adj, nodeOf, routes, stationRoutes };
    return GRAPHS[gk];
  }

  // ---------------------------------------------------------------- Dijkstra (binary heap)
  function search(G, a, b, o) {
    o = o || {};
    const { adj, ids } = G, N = adj.length, dist = new Float64Array(N).fill(Infinity), prev = new Int32Array(N).fill(-1), pe = new Array(N);
    const heap = [];
    const push = (d, n) => { heap.push([d, n]); let i = heap.length - 1; while (i > 0) { const p = (i - 1) >> 1; if (heap[p][0] <= heap[i][0]) break; [heap[p], heap[i]] = [heap[i], heap[p]]; i = p; } };
    const pop = () => { const top = heap[0], last = heap.pop(); if (heap.length) { heap[0] = last; let i = 0; for (;;) { let l = 2 * i + 1, r = l + 1, m = i; if (l < heap.length && heap[l][0] < heap[m][0]) m = l; if (r < heap.length && heap[r][0] < heap[m][0]) m = r; if (m === i) break; [heap[m], heap[i]] = [heap[i], heap[m]]; i = m; } } return top; };
    (G.stationRoutes[a] || []).forEach(r => { const n = ids.get(a + "|" + r.id + "|0"); if (n != null) { dist[n] = 0; push(0, n); } });
    const endNodes = new Set((G.stationRoutes[b] || []).map(r => ids.get(b + "|" + r.id + "|1")).filter(x => x != null));
    let end = -1;
    while (heap.length) {
      const [d, n] = pop();
      if (d > dist[n]) continue;
      if (endNodes.has(n)) { end = n; break; }
      for (const [to, c, e] of adj[n]) {
        let cost = c;
        if (e.k === "t") {
          if (o.banTransfer && e.g1 !== e.g2 && o.banTransfer.has(e.s.i)) continue;
          if (o.mode === "transfers" && e.g1 !== e.g2) cost += 1e7;           // lexicographic: fewest transfers first, then time
        } else if (o.penalty) { const f = o.penalty.get(e.id); if (f) cost = c * f; }
        const nd = d + cost;
        if (nd < dist[to]) { dist[to] = nd; prev[to] = n; pe[to] = e; push(nd, to); }
      }
    }
    if (end < 0) return null;
    const E = [];
    for (let n = end; prev[n] >= 0; n = prev[n]) E.unshift(pe[n]);
    return E;
  }

  // ---------------------------------------------------------------- timing + metrics of one route (list of edges)
  function allocate(secs) {                       // whole minutes that add up to the rounded total (largest remainder)
    const total = Math.round(secs.reduce((x, y) => x + y, 0) / 60);
    const raw = secs.map(s => s / 60), base = raw.map(Math.floor);
    let left = total - base.reduce((x, y) => x + y, 0);
    raw.map((v, i) => [v - Math.floor(v), i]).sort((p, q) => q[0] - p[0]).forEach(([, i]) => { if (left > 0) { base[i]++; left--; } });
    return { mins: base.map(v => Math.max(0, v)), total };
  }
  function timing(E) {
    const legs = []; let cur = null;
    E.forEach(e => {
      if (e.k === "r") {
        if (!cur || cur.g !== e.r.g) { cur = { type: "ride", g: e.r.g, from: e.a, to: e.b, edges: [], changeSec: 0, changes: 0 }; legs.push(cur); }
        cur.edges.push(e); cur.to = e.b;
      } else if (e.g1 !== e.g2) {
        legs.push({ type: "transfer", s: e.s, g1: e.g1, g2: e.g2, sec: e.sec, walkSec: e.w * 60, waitSec: e.waitSec || 0, meters: e.meters, src: e.src, cls: e.cls, via: e.via }); cur = null;
      } else if (cur) { cur.changeSec += e.sec; cur.changes++; }
    });
    const basis = { segments: 0, official: 0, derived: 0, estimated: 0, transfers: 0, transfersOfficial: 0, transfersDefault: 0 };
    let runSec = 0, dwellSec = 0, trSec = 0, kmTot = 0, stops = 0;
    legs.forEach(l => {
      if (l.type === "ride") {
        l.stops = l.edges.length; l.km = l.edges.reduce((x, e) => x + e.km, 0);
        l.runSec = l.edges.reduce((x, e) => x + e.sec, 0); l.stationStops = Math.max(0, l.stops - 1 - l.changes);            // a branch change is a change of train, not a through-stop (same as the graph)
        l.dwellSec = l.stationStops * CFG.dwellSeconds;
        l.sec = l.runSec + l.dwellSec + l.changeSec;
        l.tiers = { official: 0, derived: 0, estimated: 0 }; l.edges.forEach(e => { l.tiers[e.tier]++; basis.segments++; basis[e.tier]++; });
        runSec += l.runSec + l.changeSec; dwellSec += l.dwellSec; kmTot += l.km; stops += l.stops;
      } else { basis.transfers++; if (l.src === "official") basis.transfersOfficial++; else basis.transfersDefault++; trSec += l.sec; }
    });
    const al = allocate(legs.map(l => l.sec));
    legs.forEach((l, i) => { l.min = Math.max(al.mins[i], 1); });
    // keep the displayed legs adding up to the displayed total even after the 1-minute floor
    let sum = legs.reduce((x, l) => x + l.min, 0), idx = legs.map((l, i) => i).sort((p, q) => legs[q].min - legs[p].min);
    for (let k = 0; sum > al.total && k < 50; k++) { const l = legs[idx[k % idx.length]]; if (l.min > 1) { l.min--; sum--; } }
    const totalSec = runSec + dwellSec + trSec;
    return { totalSec, totalMin: Math.max(al.total, 1), runSec, dwellSec, transferSec: trSec, km: kmTot, stops, legs, basis,
      quality: basis.estimated || basis.derived ? (basis.official ? "partial" : basis.derived ? "derived" : "estimated") : (basis.transfersDefault ? "official+default" : "official") };
  }

  // ---------------------------------------------------------------- signatures / differences
  const rideIds = E => E.filter(e => e.k === "r").map(e => e.id);
  const sig = E => E.map(e => e.k === "r" ? e.id + ">" + e.b : "T" + e.s.i + e.g1 + e.g2).join(",");
  const lineSeq = E => timing(E).legs.filter(l => l.type === "ride").map(l => l.g).join(">");
  const xferSet = E => E.filter(e => e.k === "t" && e.g1 !== e.g2).map(e => e.s.i).join(",");
  function jaccard(A, B) { const a = new Set(A), b = new Set(B); let i = 0; a.forEach(x => b.has(x) && i++); return i / (a.size + b.size - i || 1); }

  // ---------------------------------------------------------------- public: ranked options
  function options(a, b, ex) {
    if (typeof ST === "undefined" || !ST[a] || !ST[b] || a === b) return null;
    const G = graph(ex);
    const fast = search(G, a, b, {});
    if (!fast) return null;
    const few = search(G, a, b, { mode: "transfers" });
    const pool = new Map();
    const add = E => { if (!E || !E.length) return; const s = sig(E); if (!pool.has(s)) { const T = timing(E); pool.set(s, { E, T, sig: s, tr: T.legs.filter(l => l.type === "transfer").length, ids: rideIds(E), lines: lineSeq(E), xs: xferSet(E) }); } };
    add(fast); add(few);
    const base = [fast, few].filter(Boolean);
    // alternates: penalise the edges of the best routes, and forbid each interchange they use, then keep what differs
    [1.25, 1.6, 2.2, 3].forEach(f => base.forEach(E => { const pen = new Map(); rideIds(E).forEach(id => pen.set(id, f)); add(search(G, a, b, { penalty: pen })); }));
    const banned = new Set(); base.forEach(E => E.forEach(e => { if (e.k === "t" && e.g1 !== e.g2) banned.add(e.s.i); }));
    banned.forEach(si => add(search(G, a, b, { banTransfer: new Set([si]) })));
    banned.forEach(si => base.forEach(E => { const pen = new Map(); rideIds(E).forEach(id => pen.set(id, 1.3)); add(search(G, a, b, { banTransfer: new Set([si]), penalty: pen })); }));
    const all = [...pool.values()];
    const best = all.slice().sort((p, q) => p.T.totalSec - q.T.totalSec || p.tr - q.tr)[0];                 // FASTEST
    const fewest = all.slice().sort((p, q) => p.tr - q.tr || p.T.totalSec - q.T.totalSec)[0];              // FEWEST TRANSFERS
    const out = [{ ...best, key: "f", label: "FASTEST" }];
    if (fewest.sig === best.sig) out[0].fewest = true, out[0].label = "FASTEST · FEWEST TRANSFERS";
    else out.push({ ...fewest, key: "t", label: "FEWEST TRANSFERS" });
    const A = CFG.alternates, limit = Math.min(best.T.totalSec * A.maxRatio, best.T.totalSec + A.maxExtraSec);
    all.filter(c => !out.some(o => o.sig === c.sig) && c.T.totalSec <= limit).sort((p, q) => p.T.totalSec - q.T.totalSec || p.tr - q.tr).forEach(c => {
      if (out.filter(o => o.key === "a").length >= A.max) return;
      // meaningfully different from EVERY route already chosen: other lines, other interchanges, or little shared track
      const different = out.every(o => o.lines !== c.lines || o.xs !== c.xs || jaccard(o.ids, c.ids) <= A.maxOverlap);
      if (different) out.push({ ...c, key: "a", label: out.some(o => o.key === "a") ? "ALTERNATE 2" : "ALTERNATE" });
    });
    // rank by time (1 = quickest); ties keep order
    const order = out.map((o, i) => [o.T.totalSec, o.tr, i]).sort((p, q) => p[0] - q[0] || p[1] - q[1] || p[2] - q[2]);
    order.forEach(([, , i], r) => { out[i].rank = r + 1; });
    return out;
  }

  window.RouteEngine = { options, timing, rideSegment, transferTime, config: CFG, model: MODEL, data: TTD, _graph: graph, _search: search };
})();
